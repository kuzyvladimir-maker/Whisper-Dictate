import Cocoa

// Clipboard + Cmd+V, then the previous clipboard is put back. The dictated text is marked
// transient so clipboard managers skip it.

final class Paster {
    private typealias Snapshot = [[(NSPasteboard.PasteboardType, Data)]]

    func paste(_ text: String, restore: Bool, restoreDelay: Double) {
        let pb = NSPasteboard.general
        let saved: Snapshot? = restore ? snapshot(pb) : nil
        pb.clearContents()
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        item.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.TransientType"))
        item.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"))
        pb.writeObjects([item])
        let ours = pb.changeCount

        postCommandV()

        guard let snap = saved else { return }
        DispatchQueue.main.asyncAfter(deadline: .now() + restoreDelay) {
            // The user copied something else meanwhile: leave it alone.
            guard pb.changeCount == ours else { return }
            pb.clearContents()
            if snap.isEmpty { return }
            let items = snap.map { pairs -> NSPasteboardItem in
                let it = NSPasteboardItem()
                for (type, data) in pairs { it.setData(data, forType: type) }
                return it
            }
            pb.writeObjects(items)
        }
    }

    func copy(_ text: String) {
        let pb = NSPasteboard.general
        pb.clearContents()
        pb.setString(text, forType: .string)
    }

    private func snapshot(_ pb: NSPasteboard) -> Snapshot {
        (pb.pasteboardItems ?? []).map { item in
            item.types.compactMap { type in item.data(forType: type).map { (type, $0) } }
        }
    }

    private func postCommandV() {
        let src = CGEventSource(stateID: .hidSystemState)
        let vKey: CGKeyCode = 9  // kVK_ANSI_V; Cmd shortcuts resolve it under Russian layouts too
        let down = CGEvent(keyboardEventSource: src, virtualKey: vKey, keyDown: true)
        let up = CGEvent(keyboardEventSource: src, virtualKey: vKey, keyDown: false)
        down?.flags = .maskCommand
        up?.flags = .maskCommand
        down?.post(tap: .cghidEventTap)
        up?.post(tap: .cghidEventTap)
    }
}
